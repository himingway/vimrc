#!/bin/bash
set -e

if [ -z "$1" ]; then
    echo "Usage: $0 <vim_runtime_path> [user1 user2 ...] or $0 <vim_runtime_path> --all"
    exit 1
fi

RUNTIME_PATH="$(cd "$1" && pwd)"
echo "Installing Awesome Vim from $RUNTIME_PATH"

# Initialize my_configs.vim from template if not present, or patch legacy winnr('h')
if [ ! -f "${RUNTIME_PATH}/my_configs.vim" ] && [ -f "${RUNTIME_PATH}/my_configs.vim.template" ]; then
    cp "${RUNTIME_PATH}/my_configs.vim.template" "${RUNTIME_PATH}/my_configs.vim"
    echo "Initialized ${RUNTIME_PATH}/my_configs.vim from my_configs.vim.template"
elif [ -f "${RUNTIME_PATH}/my_configs.vim" ]; then
    if grep -q "winnr('h')" "${RUNTIME_PATH}/my_configs.vim" 2>/dev/null; then
        sed -i.bak "s/winnr('h')/1/g" "${RUNTIME_PATH}/my_configs.vim" 2>/dev/null || sed -i "" "s/winnr('h')/1/g" "${RUNTIME_PATH}/my_configs.vim" 2>/dev/null || true
        rm -f "${RUNTIME_PATH}/my_configs.vim.bak"
        echo "Auto-patched legacy winnr('h') in ${RUNTIME_PATH}/my_configs.vim for Vim 8.0 compatibility"
    fi
fi

VIMRC="\" DO NOT EDIT THIS FILE
\" Add your own customizations in $RUNTIME_PATH/my_configs.vim

set nocompatible
set cpoptions&vim
set packpath^=$RUNTIME_PATH
set runtimepath^=$RUNTIME_PATH

source $RUNTIME_PATH/vimrcs/basic.vim
source $RUNTIME_PATH/vimrcs/filetypes.vim
source $RUNTIME_PATH/vimrcs/plugins_config.vim
source $RUNTIME_PATH/vimrcs/extended.vim

try
  source $RUNTIME_PATH/my_configs.vim
catch
endtry"

install_for_user() {
    local user="$1"
    local homepath
    homepath=$(eval echo "~$user")

    if [ ! -d "$homepath" ]; then
        echo "Skipping non-existent home directory for user: $user"
        return
    fi

    if [ -f "${homepath}/.vimrc" ]; then
        cp "${homepath}/.vimrc" "${homepath}/.vimrc.backup.$(date +%Y%m%d_%H%M%S)"
    fi

    echo "$VIMRC" > "${homepath}/.vimrc"
    if [ "$(id -u)" -eq 0 ]; then
        chown "$user":"$user" "${homepath}/.vimrc" 2>/dev/null || true
    fi
    echo "Installed the Ultimate Vim configuration for user $user successfully! Enjoy :-)"
}

if [ "$2" = "--all" ]; then
    for homepath in /home/*; do
        if [ -d "$homepath" ]; then
            user=$(basename "$homepath")
            install_for_user "$user"
        fi
    done
    echo "Installed the Ultimate Vim configuration for all users successfully! Enjoy :-)"
    exit 0
else
    SELECTED_USERS=${@:2}
    echo "Selected users: $SELECTED_USERS"
    for user in $SELECTED_USERS; do
        install_for_user "$user"
    done
    exit 0
fi
